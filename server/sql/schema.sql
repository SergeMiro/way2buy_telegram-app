-- its numeric chat_id is bound. lower() because Telegram usernames are
-- case-insensitive, and it is immutable so it can carry an index.
--
-- NOT unique: two rows legitimately share a username. The 'main' channel and the
-- legacy 'ukraine' catalogue both default to @Way2Buy_Ukraine, so a unique index
