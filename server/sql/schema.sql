-- ── changes to objects that already shipped ───────────────────────────────
--
-- CREATE TABLE IF NOT EXISTS cannot add a column to a table that exists, and it
-- does not fail either — it silently does nothing, so a database created before
-- these columns existed would keep running without them until a query broke.
-- Anything gained after the first deploy has to say so explicitly, the same rule
-- the index drops further down follow.
alter table posts    add column if not exists curated     boolean not null default false;
-- WHICH of the three sources named the brand — see parsePostText() and vision.js:
--   'text'        the caption said it. The seller's own word, right or wrong.
--   'channel'     the caption was silent and the catalogue's name answered.
--   'vision'      neither did, and the model read a logo off the photograph.
--   'vision-none' the model looked and found nothing legible. Recorded so the
--                 same photograph is not paid for twice.
--   null          nothing has answered yet — this is the backfill's work queue.
alter table posts    add column if not exists brand_source text;
alter table channels add column if not exists synced_at   timestamptz;
-- Where the deep backfill stopped, so «вся історія» resumes instead of re-reading
-- the newest pages. NULL means "start from the top".
alter table channels add column if not exists sync_cursor bigint;
-- Set once the walk reached the channel's first post; the button then has
-- nothing left to do.
alter table channels add column if not exists history_done boolean not null default false;
-- What was actually bought, as a card and not only as a line of text. Without
-- this a sale cannot be attributed to a brand, a category or a channel post, so
-- "which kind of thing sells" has to be guessed from the title. Nullable: sales
-- entered by hand, and every sale recorded before now, simply have no card.
alter table purchases add column if not exists post_id integer references posts(id) on delete set null;
alter table purchases add column if not exists article text;

do $$
begin
  -- The status CHECK is part of the table definition above, but a database
  -- created before 'gone' existed carries the old constraint (or none).
  if exists (select 1 from pg_constraint where conname = 'posts_status_check') then
    alter table posts drop constraint posts_status_check;
  end if;
  alter table posts add constraint posts_status_check
    check (status in ('published', 'hidden', 'gone'));
end $$;

