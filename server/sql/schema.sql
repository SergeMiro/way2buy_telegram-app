-- ── Did they actually buy it? ────────────────────────────────────────────
--
--  An inquiry answers "who asked about what". It does not answer the question
--  the shop actually lives on: did that person go on to buy the article, or
--  not? Nothing recorded that before, so the answer lived in Maryna's head.
--
--  One row per inquiry, opened the moment the client presses «Відправити».
--  It starts `in_progress` and stays there until a human says otherwise —
--  «no answer yet» is a real state, not an absence of data, and it is the one
--  the reminder job reads.
--
--  Maryna asked for three columns — in progress / bought / not bought — so the
--  table can be read at a glance in the Supabase editor. They are here, but
--  GENERATED from `status`: three independent booleans can be set to two trues
--  or three falses, and then no query in the app agrees with any other. One
--  writable column decides; the three read exactly as asked and cannot drift.
--  Correcting a mistake is therefore a single UPDATE of `status`, which is what
--  the pencil in the cabinet does.
create table if not exists deals (
  id            integer primary key generated by default as identity,
  customer_id   integer not null references customers(id) on delete cascade,
  -- The inquiry this grew out of. Kept unique so a re-sent request cannot open
  -- a second card for the same conversation.
  inquiry_id    integer references inquiries(id) on delete set null,
  -- Snapshot of the articles asked about, so a post edited or deleted in the
  -- channel never rewrites what the deal was about. Same reasoning as
  -- cart_events.
  items_json    jsonb not null default '[]'::jsonb,
  items_count   integer not null default 0,
  articles      text,                        -- 'CH22, DL01' — for search and DMs
  status        text not null default 'in_progress'
                check (status in ('in_progress', 'bought', 'not_bought')),
  in_progress   boolean generated always as (status = 'in_progress') stored,
  bought        boolean generated always as (status = 'bought')      stored,
  not_bought    boolean generated always as (status = 'not_bought')  stored,
  -- Optional, and only meaningful once bought: what the order came to. The
  -- money of record is still `purchases`; this is the manager's own note.
  amount_usd    numeric(12,2),
  note          text,
  decided_by    text,                        -- tg id of whoever moved it
  decided_at    timestamptz,
  -- The nudge loop. `reminders` is the round number, so the dedupe key of the
  -- next reminder is different from the last one's without a timer anywhere.
  reminded_at   timestamptz,
  reminders     integer not null default 0,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

