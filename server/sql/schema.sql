-- ─────────────────────────────────────────────────────────────────────────
--  Access posture. Every query in this app goes through the Express server
--  using the service_role key, so no table is meant to be reachable with the
--  public anon key. RLS on with zero policies denies anon and authenticated
--  outright, while service_role bypasses RLS — deny-by-default rather than a
--  policy someone has to remember to write.
--
--  The role grants are wrapped in a guard because anon/authenticated exist only
--  on Supabase; the same file has to run against PGlite in the tests.
-- ─────────────────────────────────────────────────────────────────────────

do $$
declare t text;
begin
  foreach t in array array[
    'customers', 'purchases', 'redemptions', 'channels', 'posts', 'events',
    'discount_rules', 'holidays', 'campaigns', 'promo_codes', 'birthday_claims',
    'inquiries', 'cart_items', 'cart_events', 'notifications',
    'ai_conversations', 'ai_messages', 'ai_proposals', 'scheduler_lock',
    'heartbeat'
  ]
  loop
    execute format('alter table %I enable row level security', t);
    if exists (select 1 from pg_roles where rolname = 'anon') then
      execute format('revoke all on table %I from anon, authenticated', t);
    end if;
  end loop;

  -- The views run with the privileges of their owner, so they must not be a
  -- way around the tables' RLS for a public key either.
  if exists (select 1 from pg_roles where rolname = 'anon') then
    execute 'revoke all on v_customer_overview, v_purchase_margin, v_item_popularity'
         || ' from anon, authenticated';
  end if;
end $$;
