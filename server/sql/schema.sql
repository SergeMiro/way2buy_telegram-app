-- ─────────────────────────────────────────────────────────────────────────
--  schema.sql — the Way2Buy schema on PostgreSQL (Supabase).
--
--  Applied on every boot and idempotent (CREATE ... IF NOT EXISTS), which is
--  what the SQLite migrate() did too. The same file runs against PGlite in the
--  test suite, so the tests exercise the real dialect.
--
--  Types are deliberate, not mechanical ports of the SQLite ones:
--    • money      → numeric(12,2). SQLite REAL is binary floating point; money
--                   in a float is a bug waiting for a rounding complaint.
--    • dates      → timestamptz. Everything the app writes is already UTC ISO.
--    • flags      → boolean.
--    • *_json     → jsonb, so the dashboard can query inside them.
--
--  Three columns keep their text type on purpose:
--    • customers.birthday — parseBirthday() accepts a year-less 'MM-DD', which
--      a date column cannot hold. See docs/BUSINESS-LOGIC.md §7.
--    • cart_events.ym / .y — pre-computed buckets. to_char() over a timestamptz
--      is not IMMUTABLE, so Postgres refuses to index it; these columns are how
--      the popularity reports stay indexable.
--    • events.meta — free text ('5 переглядів'), never JSON.
--
--  CHECK constraints are only on closed value sets. Columns like
--  notifications.kind or campaigns.status grow with the product (the scheduler
--  alone writes cost_missing_digest, inquiry_sent, bday_mismatch), so pinning
--  them would turn a new feature into a production insert failure.
-- ─────────────────────────────────────────────────────────────────────────

-- ── Customers & loyalty ──────────────────────────────────────────────────

create table if not exists customers (
  id                   integer primary key generated by default as identity,
  tg_user_id           text unique,
  login                text,
  name                 text not null,
  phone                text,
  email                text,
  -- 'YYYY-MM-DD' or a year-less 'MM-DD'. Text, not date: see the header.
  birthday             text,
  city                 text,
  address              text,
  birthday_source      text,                    -- 'claim' | 'admin' | 'seed'
  birthday_recorded_at timestamptz,
  consent              boolean not null default true,
  notes                text,
  created_at           timestamptz not null default now()
);

create table if not exists purchases (
  id               integer primary key generated by default as identity,
  customer_id      integer not null references customers(id) on delete cascade,
  title            text,
  -- what the client paid, normalised to USD — the only figure cashback reads
  amount_usd       numeric(12,2) not null,
  -- what the client actually saw (e.g. 60000 UAH), for the history screen
  orig_amount      numeric(14,2),
  orig_currency    text default 'USD',
  source_channel   text,
  invoice_ref      text,
  status           text default 'confirmed',
  -- the profit side: everything Maryna spent (factory + shipping + fees).
  -- Deliberately nullable — the sale is known now, the cost arrives later, and
  -- the scheduler chases the gap.
  cost_usd         numeric(12,2),
  cost_note        text,
  cost_entered_at  timestamptz,
  cost_reminded_at timestamptz,
  discount_usd     numeric(12,2) default 0,
  created_at       timestamptz not null default now()
);

create table if not exists redemptions (
  id          integer primary key generated by default as identity,
  customer_id integer not null references customers(id) on delete cascade,
  amount_usd  numeric(12,2) not null,
  note        text,
  created_at  timestamptz not null default now()
);

