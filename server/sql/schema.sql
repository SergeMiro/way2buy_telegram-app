-- ─────────────────────────────────────────────────────────────────────────
--  schema.sql — the Way2Buy schema on PostgreSQL (Supabase).
--
--  Applied on every boot and idempotent (CREATE ... IF NOT EXISTS), which is
--  what the SQLite migrate() did too. The same file runs against PGlite in the
--  test suite, so the tests exercise the real dialect.
--
--  Types are deliberate, not mechanical ports of the SQLite ones:
--    • money      → numeric(12,2). SQLite REAL is binary floating point; money
--                   in a float is a bug waiting for a rounding complaint.
--    • dates      → timestamptz. Everything the app writes is already UTC ISO.
--    • flags      → boolean.
--    • *_json     → jsonb, so the dashboard can query inside them.
--
--  Three columns keep their text type on purpose:
--    • customers.birthday — parseBirthday() accepts a year-less 'MM-DD', which
--      a date column cannot hold. See docs/BUSINESS-LOGIC.md §7.
--    • cart_events.ym / .y — pre-computed buckets. to_char() over a timestamptz
--      is not IMMUTABLE, so Postgres refuses to index it; these columns are how
--      the popularity reports stay indexable.
--    • events.meta — free text ('5 переглядів'), never JSON.
--
--  CHECK constraints are only on closed value sets. Columns like
--  notifications.kind or campaigns.status grow with the product (the scheduler
--  alone writes cost_missing_digest, inquiry_sent, bday_mismatch), so pinning
--  them would turn a new feature into a production insert failure.
-- ─────────────────────────────────────────────────────────────────────────

