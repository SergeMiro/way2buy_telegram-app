-- Idempotent materialisation (R-02): exactly one code per customer per campaign
-- per calendar year. The year is derived at UTC because that is the clock the
-- app writes in; `at time zone` on a literal zone is immutable, so this is
-- indexable — extract() straight off a timestamptz is not.
create unique index if not exists uq_promo_campaign_customer_year
  on promo_codes (campaign_id, customer_id,
                  extract(year from (created_at at time zone 'UTC')))
  where campaign_id is not null;

