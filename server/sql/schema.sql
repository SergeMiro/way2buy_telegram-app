-- ─────────────────────────────────────────────────────────────────────────
--  Views — read-only, for browsing the data in the Supabase table editor and
--  for ad-hoc reporting. The application does not depend on them: business
--  logic stays in the server modules, where the tests can reach it.
-- ─────────────────────────────────────────────────────────────────────────

create or replace view v_customer_overview
  with (security_invoker = true) as
select
  c.id,
  c.name,
  c.login,
  c.city,
  c.birthday,
  count(p.id)                                        as purchase_count,
  coalesce(sum(p.amount_usd), 0)                     as spent_usd,
  coalesce(sum(p.amount_usd) filter (where p.amount_usd >= 2000), 0) as qualifying_usd,
  coalesce((select sum(r.amount_usd) from redemptions r where r.customer_id = c.id), 0) as redeemed_usd,
  max(p.created_at)                                  as last_purchase_at,
  c.created_at
from customers c
left join purchases p on p.customer_id = c.id and p.status = 'confirmed'
group by c.id;

comment on view v_customer_overview is
  'Per-customer spend rollup for browsing. Cashback and tiers are computed in server/loyalty.js — this view is not the source of truth for them.';

create or replace view v_purchase_margin
  with (security_invoker = true) as
select
  p.id,
  p.customer_id,
  c.name as customer_name,
  p.title,
  p.amount_usd,
  p.cost_usd,
  case when p.cost_usd is null then null
       else p.amount_usd - p.cost_usd - coalesce(p.discount_usd, 0) end as margin_usd,
  case when p.cost_usd is null or p.amount_usd = 0 then null
       else round(((p.amount_usd - p.cost_usd - coalesce(p.discount_usd, 0)) / p.amount_usd) * 100, 1)
  end as margin_pct,
  p.cost_usd is null as cost_pending,
  p.source_channel,
  p.created_at
from purchases p
join customers c on c.id = p.customer_id;

comment on view v_purchase_margin is
  'Sale vs factory cost per order. cost_pending marks the rows the scheduler is still chasing.';

create or replace view v_item_popularity
  with (security_invoker = true) as
select
  ce.post_id,
  ce.title,
  ce.article,
  ce.channel,
  ce.ym,
  count(*) filter (where ce.action = 'added')   as adds,
  count(*) filter (where ce.action = 'sent')    as sends,
  count(*) filter (where ce.action = 'removed') as removes,
  count(distinct ce.customer_id)                as people
from cart_events ce
group by ce.post_id, ce.title, ce.article, ce.channel, ce.ym;

comment on view v_item_popularity is
  'What was tried on, by month. Reads the append-only journal, so it survives posts being edited or deleted.';

