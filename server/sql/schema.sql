-- resolveChannel(): a channel is matched by @username on its first post, then
-- its numeric chat_id is bound. lower() because Telegram usernames are
-- case-insensitive, and it is immutable so it can carry an index.
--
-- NOT unique: two rows legitimately share a username. The 'main' channel and the
-- legacy 'ukraine' catalogue both default to @Way2Buy_Ukraine, so a unique index
-- here fails on a clean seed.
--
-- The drop is deliberate. An earlier version of this file made the index UNIQUE,
-- and a file built out of CREATE ... IF NOT EXISTS cannot correct an object that
-- already exists — re-applying it would silently leave the old constraint in
-- place, and inserts would keep failing. Any statement that changes a previously
-- shipped object has to say so explicitly, like this one.
drop index if exists uq_channels_username_lower;
